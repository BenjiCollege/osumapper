from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from osumapper.difficulty import STANDARD_DIFFICULTY_KEYS
from osumapper.errors import InputError
from osumapper.training.config import DatasetPaths
from osumapper.training.splits import load_split
from osumapper.training.storage import read_json, write_json


def build_dataset_benchmark(
    *,
    dataset_root: Path | None = None,
    output: Path | None = None,
) -> dict[str, Any]:
    """Freeze the curated-data contract used by a model training run."""
    paths = DatasetPaths.at(dataset_root)
    manifest = read_json(paths.splits / "manifest.json", default=None)
    if manifest is None:
        raise InputError("Dataset has not been split. Run `osumapper dataset split` first.")

    splits = {
        name: load_split(name, dataset_root=paths.root) for name in ("train", "validation", "test")
    }
    all_rows = [row for rows in splits.values() for row in rows]
    song_assignments: dict[str, str] = {}
    leakage: list[dict[str, str]] = []
    tier_songs: dict[str, set[str]] = defaultdict(set)
    tier_maps: Counter[str] = Counter()
    object_types: Counter[str] = Counter()
    creators: Counter[str] = Counter()
    suspicious: list[dict[str, Any]] = []
    for split, rows in splits.items():
        for row in rows:
            song_id = str(row["song_id"])
            previous = song_assignments.setdefault(song_id, split)
            if previous != split:
                leakage.append({"song_id": song_id, "first": previous, "second": split})
            tier = str(row.get("difficulty_tier", "unknown"))
            tier_maps[tier] += 1
            tier_songs[tier].add(song_id)
            object_types["circle"] += int(row.get("circle_count", 0))
            object_types["slider"] += int(row.get("slider_count", 0))
            object_types["spinner"] += int(row.get("spinner_count", 0))
            creator = str(row.get("creator", "")).strip()
            creators[creator] += 1
            combined = f"{creator} {row.get('version', '')}".casefold()
            reasons: list[str] = []
            if bool(row.get("is_converted")):
                reasons.append("converted")
            if any(token in combined for token in ("osumapper", "auto-generated", "autogenerated")):
                reasons.append("possibly_generated")
            if reasons:
                suspicious.append(
                    {
                        "map_id": row["map_id"],
                        "map_path": row["map_path"],
                        "reasons": reasons,
                    }
                )

    total_objects = sum(object_types.values())
    expert_maps = tier_maps["expert"] + tier_maps["expert-plus"]
    test_tier_songs = {
        tier: len({str(row["song_id"]) for row in splits["test"] if row["difficulty_tier"] == tier})
        for tier in STANDARD_DIFFICULTY_KEYS
    }
    gates = {
        "at_least_100_trusted_songs": len(song_assignments) >= 100,
        "at_least_300_expert_maps": expert_maps >= 300,
        "at_least_30_test_songs_per_tier": all(
            test_tier_songs[tier] >= 30 for tier in STANDARD_DIFFICULTY_KEYS
        ),
        "all_maps_good": all(str(row.get("rating")) == "good" for row in all_rows),
        "standard_only": all(int(row.get("mode", -1)) == 0 for row in all_rows),
        "no_song_leakage": not leakage,
        "no_suspicious_generated_or_converted_maps": not suspicious,
        "contains_circles_sliders_and_spinners": all(object_types[kind] for kind in object_types),
    }
    report: dict[str, Any] = {
        "benchmark_version": 1,
        "dataset_root": str(paths.root),
        "dataset_sha256": manifest["dataset_sha256"],
        "seed": manifest["seed"],
        "ratios": manifest["ratios"],
        "status": ("production-candidate" if all(gates.values()) else "curated-prototype"),
        "songs": len(song_assignments),
        "maps": len(all_rows),
        "splits": {
            name: {
                "songs": len({str(row["song_id"]) for row in rows}),
                "maps": len(rows),
            }
            for name, rows in splits.items()
        },
        "difficulty_tiers": {
            tier: {"maps": tier_maps[tier], "songs": len(tier_songs[tier])}
            for tier in STANDARD_DIFFICULTY_KEYS
        },
        "test_songs_per_tier": test_tier_songs,
        "object_types": {
            kind: {
                "count": count,
                "ratio": count / total_objects if total_objects else 0.0,
            }
            for kind, count in object_types.items()
        },
        "expert_and_expert_plus_maps": expert_maps,
        "creators": dict(creators.most_common()),
        "suspicious_maps": suspicious,
        "song_leakage": leakage,
        "gates": gates,
        "notes": [
            "Production gates are intentionally strict and do not make a prototype look ready.",
            "A separate manually selected challenge set is still required before release claims.",
        ],
    }
    destination = (output or (paths.root / "benchmark_manifest.json")).expanduser().resolve()
    write_json(destination, report)
    report["output"] = str(destination)
    return report
